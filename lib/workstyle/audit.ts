import { ASSESSMENT_VERSION, followUps, MAX_FOLLOW_UPS, questions } from "./questions.ts"
import { chapterIds, chapters, dimensionIds, dimensions } from "./dimensions.ts"
import { CONTEXT_SIGNALS, CONTEXT_SPREAD, CLEAR_LEAN, FLEXIBLE_SPREAD, MILD_LEAN } from "./interpret.ts"
import { CORE_WEIGHT, CROSS_WEIGHT, evidenceMaxima, primaryTotals, SCORING_VERSION } from "./scoring.ts"
import { validateBank } from "./validate.ts"
import type { Effect, FollowUp, Question } from "./types.ts"

// Generates docs/workstyle/question-bank-audit.md and docs/workstyle/questions-and-responses.txt from the
// bank itself, so neither can drift. Run `npm run workstyle:audit` after changing the bank; a test fails
// if either file is out of date.

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\n/g, " ")
const code: Record<string, string> = { thinking: "T", structure: "S", decisions: "D", focus: "F", communication: "M", collaboration: "A", change: "X", feedback: "B" }
const signed = (value: number) => (value > 0 ? `+${value}` : `${value}`)
const effectText = (effect: Effect) => (effect.context ? `${code[effect.dimension]} context` : `${code[effect.dimension]}${signed(effect.value)}`)

function optionsText(question: Question): string {
  if (question.format === "scale") {
    return `5 stops, canonical: −2 “${cell(question.left)}” · −1 · 0 (context) · +1 · +2 “${cell(question.right)}”. Shown ${question.flip ? "flipped (statements swapped)" : "unflipped"}.`
  }
  return question.options
    .map((option) => `${cell(option.label)} (${option.effects.map(effectText).join(", ")})${option.last ? " [last]" : ""}`)
    .join("<br>")
}

function contributionText(question: Question): string {
  const weight = question.primary ? `core ${code[question.primary]} ×${CORE_WEIGHT}` : `cross-dimension ×${CROSS_WEIGHT}`
  const how: Record<Question["format"], string> = {
    choice: "value of the chosen option",
    multi: `mean of the selected options’ values (pick up to ${"max" in question ? question.max : 0})`,
    rank: "weighted mean, position weights 4, 3, 2, 1",
    split: "share-weighted mean",
    scale: "stop value (−2 to +2)",
  }
  return `${weight}; ${how[question.format]}`
}

function triggerText(followUp: FollowUp): string {
  const trigger = followUp.trigger
  if (trigger.kind === "conflict") {
    return `Any of ${trigger.dimensions.map((id) => dimensions[id].short.toLowerCase()).join(", ")} is conflicted (reads “depends on context”, with at least two answers)`
  }
  return `${trigger.questionId} points the opposite way from the rest of the profile on any dimension, by ${trigger.minShift} or more`
}

export function renderAudit(): string {
  const report = validateBank()
  const maxima = evidenceMaxima()
  const totals = primaryTotals()
  const lines: string[] = []

  lines.push("# Question-bank audit", "")
  lines.push(
    "> Generated by `npm run workstyle:audit` from `lib/workstyle/questions.ts`. Do not edit by hand; a test fails if this file is out of date.",
    "",
    `- Assessment version: **${ASSESSMENT_VERSION}**`,
    `- Scoring version: **${SCORING_VERSION}**`,
    `- Questions: **${questions.length}** · adaptive follow-ups defined: **${followUps.length}** (at most **${MAX_FOLLOW_UPS}** asked per person, each optional)`,
    `- Reading thresholds (−2…+2 scale): clear lean |mean| ≥ ${CLEAR_LEAN * 2}, mild lean ≥ ${MILD_LEAN * 2}, flexible spread < ${FLEXIBLE_SPREAD * 2}, depends on context at spread ≥ ${CONTEXT_SPREAD * 2} or ${CONTEXT_SIGNALS}+ context signals`,
    "",
    "This audit shows **structural** coverage and scoring reachability. It cannot show that the questions measure what they intend to measure; that needs data (see `methodology.md`, “Validation plan”).",
    "",
  )

  lines.push("## Coverage by dimension", "")
  lines.push("| Dimension | Core items | Cross items | Evidence available | Formats used (core) | Largest single-question share |", "| --- | ---: | ---: | ---: | --- | ---: |")
  for (const id of dimensionIds) {
    const own = questions.filter((question) => question.primary === id)
    const cross = questions.filter((question) => question.primary === null && "options" in question && question.options.some((option) => option.effects.some((effect) => effect.dimension === id)))
    const formats = [...new Set(own.map((question) => question.format))].join(", ")
    lines.push(`| ${dimensions[id].title} (${code[id]}) | ${totals[id]} | ${cross.length} | ${maxima[id].toFixed(1)} | ${formats} | ${(100 / maxima[id]).toFixed(0)}% |`)
  }
  lines.push("")

  lines.push("## Chapters and formats (in the order asked)", "")
  for (const chapter of chapterIds) {
    const own = questions.filter((question) => question.chapter === chapter)
    lines.push(`- **${chapters[chapter].number} · ${chapters[chapter].title}**: ${own.map((question) => `${question.id} ${question.primary ? code[question.primary] : "cross"} (${question.format})`).join(" → ")}`)
  }
  lines.push("")
  const counts = new Map<string, number>()
  for (const question of questions) counts.set(question.format, (counts.get(question.format) ?? 0) + 1)
  lines.push(`Format mix: ${[...counts.entries()].map(([format, count]) => `${format} ${count}`).join(" · ")}.`, "")

  lines.push("## Question matrix", "")
  lines.push("| ID | Ch. | Format | Dimension | Prompt | Answer options (scores) | Scoring contribution |")
  lines.push("| --- | ---: | --- | --- | --- | --- | --- |")
  for (const question of questions) {
    lines.push(
      `| ${question.id} | ${chapters[question.chapter].number} | ${question.format} | ${question.primary ? code[question.primary] : "cross"}${question.tag ? ` (${question.tag})` : ""} | ${cell(question.prompt)} | ${optionsText(question)} | ${cell(contributionText(question))} |`,
    )
  }
  lines.push("")

  lines.push("## Adaptive follow-ups", "")
  lines.push("Any option scores 0 and records the person’s own “it depends on…” note. Follow-ups are optional, asked at most once, and cannot trigger other follow-ups. Private follow-ups are never part of a shared profile.", "")
  lines.push("| ID | Asked at end of | Trigger | Options → context |", "| --- | --- | --- | --- |")
  for (const followUp of followUps) {
    lines.push(
      `| ${followUp.id}${followUp.private ? " (private)" : ""} | ${chapters[followUp.chapter].number} · ${chapters[followUp.chapter].title} | ${cell(triggerText(followUp))} | ${followUp.options.map((option) => `${cell(option.label)} → \`${option.context}\``).join("<br>")} |`,
    )
  }
  lines.push("")

  lines.push("## Automated checks", "")
  lines.push(report.errors.length ? `**${report.errors.length} error(s):**` : "**Errors: none.**", "")
  for (const error of report.errors) lines.push(`- ${error}`)
  lines.push(report.warnings.length ? `**${report.warnings.length} warning(s):**` : "**Warnings: none.**", "")
  for (const warning of report.warnings) lines.push(`- ${warning}`)
  lines.push(
    "",
    "Checks performed: missing and duplicate ids · option scores within −2…+2 · both poles of each core item reachable (by enumerating every possible answer) · multi-select limits stated in the hint · no two adjacent questions on the same dimension · option length ≤ 110 characters · no em dashes or straight quotes in user-facing text · follow-up triggers, options and authored context lines · every dimension has ≥ 3 core questions · no single question supplies > 40% of a dimension’s evidence · near-duplicate prompts · same-format runs · slider orientation variety.",
    "",
    "## Known overlap to watch in pilot data",
    "",
    "- **q01 / q08** both ask when a person thinks aloud versus alone (an idea coming together; a fast meeting).",
    "- **q10 / q17** both ask what makes a person comfortable deciding without proof.",
    "- **q13 / q19 / q25** all concern the timing of challenge and feedback; q25 (ranking) is the most likely to correlate with the other two.",
    "- **q03 / q11 / q15** all measure aspects of one dimension (focus); q03 and q15 share the “uninterrupted time” idea.",
    "",
    "If pilot data show item pairs correlating above ≈ 0.8 across respondents, merge or replace one of the pair.",
    "",
  )
  return lines.join("\n")
}

// ───────────────────────── Questions and responses (for reviewers) ─────────────────────────

const FORMAT_LABEL: Record<Question["format"], string> = {
  choice: "Choose one",
  multi: "Choose all that apply (limited)",
  rank: "Rank the options",
  split: "Divide units between the options",
  scale: "Slide to a position on a 5-point scale",
}

const wrap = (text: string, indent: string, width = 92) => {
  const out: string[] = []
  let line = ""
  for (const word of text.split(" ")) {
    if (line && (indent + line + " " + word).length > width) {
      out.push(indent + line)
      line = word
    } else line = line ? `${line} ${word}` : word
  }
  if (line) out.push(indent + line)
  return out
}

/** Every question, option and follow-up as a participant meets them, for sharing with reviewers. */
export function renderQuestionsExport(): string {
  const rule = "=".repeat(92)
  const lines: string[] = [
    "WORKSHAPE WORK-STYLE ASSESSMENT: ALL QUESTIONS AND RESPONSES",
    `Assessment version ${ASSESSMENT_VERSION}. Generated from lib/workstyle/questions.ts by \`npm run workstyle:audit\`.`,
    "",
    "Shown to participants as written. Options are shuffled for each participant (options marked “stays last” never move);",
    "ranking items start in a random order. Scoring values are not shown to participants.",
    `Up to ${MAX_FOLLOW_UPS} optional follow-up questions are asked at the end of a chapter, only when the earlier answers call for them.`,
    "Every question can be skipped. The last step is an optional sentence to finish in the participant’s own words.",
    "",
  ]
  let number = 0
  for (const chapterId of chapterIds) {
    const chapter = chapters[chapterId]
    lines.push(rule, `CHAPTER ${chapter.number} · ${chapter.title.toUpperCase()}`, ...wrap(chapter.intro, ""), rule, "")
    for (const question of questions.filter((candidate) => candidate.chapter === chapterId)) {
      number += 1
      lines.push(`Q${number}  [${question.id}]  ${FORMAT_LABEL[question.format]}${question.format === "multi" ? ` (up to ${question.max})` : ""}`)
      lines.push(...wrap(question.prompt, "    "))
      if (question.hint) lines.push(`    (${question.hint})`)
      if (question.format === "scale") {
        const [shownLeft, shownRight] = question.flip ? [question.right, question.left] : [question.left, question.right]
        lines.push(`      ◀  ${shownLeft}`, `      ▶  ${shownRight}`, "      Five stops: far left, a little left, in the middle (“it depends”), a little right, far right.")
      } else {
        question.options.forEach((option, index) => lines.push(`      ${"abcdefgh"[index]}) ${option.label}${option.last ? "  [stays last]" : ""}`))
      }
      lines.push("")
    }
    for (const followUp of followUps.filter((candidate) => candidate.chapter === chapterId)) {
      lines.push(`Follow-up  [${followUp.id}]  Optional, only if triggered: ${triggerText(followUp)}`, ...wrap(followUp.prompt, "    "))
      followUp.options.forEach((option, index) => lines.push(`      ${"abcdefgh"[index]}) ${option.label}`))
      lines.push("")
    }
  }
  lines.push(rule, "LAST STEP · OPTIONAL", rule, "", "Finish the sentence, in your own words: “It helps me most when the people I work with…”", "    (Up to 400 characters. Shown in the participant’s own words in their guide. Stays on their device.)", "")
  return lines.join("\n")
}
